// Deterministic 7-char "commit hash" from any string, so each project/experience
// gets a stable git-style short SHA in the UI. Not cryptographic — purely cosmetic.
export function shortHash(input: string): string {
  let h = 0x811c9dc5;
  for (let i = 0; i < input.length; i++) {
    h ^= input.charCodeAt(i);
    h = Math.imul(h, 0x01000193);
  }
  return (h >>> 0).toString(16).padStart(8, "0").slice(0, 7);
}
